"""
    该案例演示了字符串类型
"""
# 创建字符串
str1 = "hello world"

# 访问字符串
print(str1[2])
print(str1[1:6])
print(str1[2:])

#字符串相加
str1 = "hello"
str2 = "world"
print(str2+" "+str1)

# 字符串乘法
print("hello" * 2)
# 成员运算
print("hello" in str1)

# 原始字符串
print("hello \n world")
print(r"hello\nworld")
print(R"hello\nworld")
